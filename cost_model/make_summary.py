"""Write the engine's headline results as a markdown note for the report writer.

  python make_summary.py  ->  research_notes/Self hosting LLM cost Pune/model_results.md
"""
from pathlib import Path

import yaml

from engine import run_llm, run_ocr
from inputs import DATA, Data

OUT = Path(__file__).parent.parent / "research_notes" / "Self hosting LLM cost Pune" / "model_results.md"
BASE = {"uptime": "24x7", "itc": 1, "spare": 0, "years": 3}
LAKH = 1e5
# throughput uncertainty by evidence class (see calibration.yaml): measured pair / inherited pair
MEASURED = {"glm53/b200": 0.10, "glm53/mi355x": 0.10, "glm53/h200": 0.15, "kimi27/h200": 0.15,
            "kimi27/b200": 0.15, "dsv4pro/b200": 0.20}
UNMEASURED = 0.25
NAMES = {"glm53": "GLM-5.3", "dsv4pro": "DeepSeek V4 Pro", "kimi27": "Kimi K2.7 Code"}


def L(x):
    return f"{x / LAKH:,.1f}"


def best(d, model, wl, users, speed, metric, lv=BASE, extra=None, gpus=None):
    """Cheapest feasible (gpu, precision) for a metric; returns (value, row)."""
    top = None
    for gpu in gpus or d.scen["grid"]["gpus"]:
        for prec in d.models[model]["precisions"]:
            row = d.llm_row(model, prec, gpu, wl, users, speed, **lv)
            if extra:
                row.update(extra)
            v = run_llm(row)
            if v["feasible"] == 1 and (top is None or v[metric] < top[0]):
                top = (v[metric], {**v, "gpu": gpu, "precision": prec})
    return top


def band(d, model, gpu, prec, wl, users, speed, lv=BASE):
    u = MEASURED.get(f"{model}/{gpu}", UNMEASURED)
    out = []
    for s in (1 + u, 1 - u):   # optimistic, pessimistic
        row = d.llm_row(model, prec, gpu, wl, users, speed, **lv)
        row["e_bw_eff"] *= s
        row["e_flop_eff"] *= s
        row["e_pf_eff"] *= s
        row["e_seq_us"] /= s
        out.append(run_llm(row))
    return u, out


def main():
    d = Data()
    md = ["# Model results (generated by cost_model/make_summary.py)", "",
          "All figures INR per month unless stated, ex-GST where ITC applies.",
          "Base levers: 24/7, GST input credit claimed, no spare node, 3-year horizon, HT commercial power tariff",
          "(Stark Digital is not a registered IT/ITeS unit). FX Rs95.18/USD. 'Own room' = bought and run in a new server room in Baner;",
          "'colo' = bought and hosted in a Pune (air) / Navi Mumbai (liquid) colocation; 'rent' = cheapest cloud option + 1 MLOps engineer.",
          "Monthly buy/colo cost = capex x capital-recovery factor (11%, 20% resale) + opex. Source data and formulas: cost_model/.", ""]

    # 1. headline: cheapest option per model x workload at 90 users / 30 tok/s, and 50 users / 20 tok/s
    for users, speed in ((90, 30), (50, 20), (90, 50)):
        md += [f"## Cheapest option per model and workload: {users} users, {speed} tok/s per user", "",
               "| Model | Workload | Best own-room (Rs lakh/mo) | GPU / precision / nodes | Best colo | Best rent (incl. staff) | Rent GPU | Buy breakeven vs rent (months) | Own-room range (throughput uncertainty) |",
               "|---|---|---|---|---|---|---|---|---|"]
        for m in d.scen["grid"]["models"]:
            for wl in d.scen["grid"]["workloads"]:
                b = best(d, m, wl, users, speed, "buy_m")
                r = best(d, m, wl, users, speed, "rent_m")
                c = best(d, m, wl, users, speed, "colo_m")
                if not b:
                    md.append(f"| {NAMES[m]} | {wl} | not feasible | | | | | | |")
                    continue
                v = b[1]
                u, (opt, pes) = band(d, m, v["gpu"], v["precision"], wl, users, speed)
                md.append(f"| {NAMES[m]} | {wl} | {L(b[0])} | {v['gpu']} / {v['precision']} / {v['nodes']:.0f} "
                          f"| {L(c[0])} ({c[1]['gpu']}) | {L(r[0])} | {r[1]['gpu']} {r[1]['precision']} "
                          f"| {v['breakeven_m']:.0f} | {L(opt['buy_m'])}-{L(pes['buy_m'])} (+/-{u:.0%}; nodes {opt['nodes']:.0f}-{pes['nodes']:.0f}) |")
        md.append("")

    # 1b. NVIDIA-only (MI355X purchase price is inferred and its cheapest rental is a "from" contract rate)
    nv = ["h200", "b200", "b300", "gb300nvl72"]
    md += ["## NVIDIA-only cheapest option: 90 users, 30 tok/s (MI355X excluded)", "",
           "| Model | Workload | Own room Rs lakh/mo | GPU / precision / nodes | Colo | Rent (incl. staff) | Rent GPU |", "|---|---|---|---|---|---|---|"]
    for m in d.scen["grid"]["models"]:
        for wl in d.scen["grid"]["workloads"]:
            b = best(d, m, wl, 90, 30, "buy_m", gpus=nv)
            r = best(d, m, wl, 90, 30, "rent_m", gpus=nv)
            c = best(d, m, wl, 90, 30, "colo_m", gpus=nv)
            if not b:
                md.append(f"| {NAMES[m]} | {wl} | not feasible | | | | |")
                continue
            v = b[1]
            md.append(f"| {NAMES[m]} | {wl} | {L(b[0])} | {v['gpu']} / {v['precision']} / {v['nodes']:.0f} | {L(c[0])} ({c[1]['gpu']}) | {L(r[0])} | {r[1]['gpu']} {r[1]['precision']} |")
    md.append("")

    # 2. precision comparison (fixed GPU per model)
    md += ["## Precision comparison: agent_128k, 90 users, 30 tok/s, cheapest GPU per precision", "",
           "| Model | Precision | Weights GB | Feasible | GPU | Nodes | Own-room Rs lakh/mo | Rent Rs lakh/mo | KV per user at mean ctx (GB) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for m in d.scen["grid"]["models"]:
        for prec in d.models[m]["precisions"]:
            top = None
            for gpu in d.scen["grid"]["gpus"]:
                v = run_llm(d.llm_row(m, prec, gpu, "agent_128k", 90, 30, **BASE))
                key = (v["feasible"] == 0, v["buy_m"])
                if top is None or key < top[0]:
                    top = (key, gpu, v)
            _, gpu, v = top
            md.append(f"| {NAMES[m]} | {prec} | {v['m_weights_gb']:,.0f} | {'yes' if v['feasible'] else 'NO (memory/cost only)'} | {gpu} "
                      f"| {v['nodes']:.0f} | {L(v['buy_m'])} | {L(v['rent_m'])} | {v['kv_seq_gb']:.1f} |")
    md.append("")

    # 3. levers on one reference config
    ref = ("glm53", "fp8", "b200", "agent_128k", 90, 30)
    md += [f"## Lever sensitivity on GLM-5.3 FP8, 8xB200, agent_128k, 90 users, 30 tok/s", "",
           "| Lever change | Own room Rs lakh/mo | Colo | Rent (today) | Rent (avg over horizon) | Nodes |", "|---|---|---|---|---|---|"]
    cases = [("Base (24/7, ITC, N, 3 yr, commercial tariff)", BASE, {}),
             ("Business hours only", {**BASE, "uptime": "bh"}, {}),
             ("No GST input credit", {**BASE, "itc": 0}, {}),
             ("N+1 spare node", {**BASE, "spare": 1}, {}),
             ("5-year horizon", {**BASE, "years": 5}, {}),
             ("Registered IT/ITeS unit (industrial tariff, duty-exempt)", BASE, {"s_it_tariff": 1}),
             ("Rental prices fall 25%/yr", BASE, {"p_rent_decline": 0.25}),
             ("Resale 0% (instead of 20%)", BASE, {"k_resale": 0.0}),
             ("TP attention instead of DP-attention", BASE, {"e_dp_attn": 0})]
    for label, lv, extra in cases:
        row = d.llm_row(*ref, **lv)
        row.update(extra)
        v = run_llm(row)
        md.append(f"| {label} | {L(v['buy_m'])} | {L(v['colo_m'])} | {L(v['rent_m'])} | {L(v['rent_tco'] / (12 * v['s_years']))} | {v['nodes']:.0f} |")
    md.append("")

    # 4. cost breakdown for the reference config
    v = run_llm(d.llm_row(*ref, **BASE))
    md += ["## Cost breakdown, same reference config (own room, 24/7)", "", "| Item | Rs |", "|---|---|"]
    for k, lab in [("hw_landed", "Landed hardware (servers, network, storage; IGST credited)"), ("fac_capex", "Facility build (electrical, UPS, DG, cooling, civil, fire, racks)"),
                   ("buy_capex", "Total capex"), ("buy_capex_m", "Capex as monthly charge"), ("power_m", "Electricity / month"),
                   ("diesel_m", "DG diesel / month"), ("staff_room_m", "Staff / month"), ("space_m", "Space rent / month"),
                   ("insure_m", "Insurance / month"), ("hw_amc_m", "Hardware AMC (avg) / month"), ("buy_opex", "Opex / month"),
                   ("buy_m", "All-in / month"), ("it_kw_max", "IT load kW (max)"), ("kva_it", "Contract demand kVA"),
                   ("needs_ht", "Needs HT connection (1=yes)"), ("speed_actual", "Per-user tok/s at peak"), ("ttft", "TTFT idle replica (s)"),
                   ("out_tok_m", "Output tokens / month"), ("per_mtok_out_buy", "Rs per 1M output tokens (own room)"),
                   ("cmp_out_overhead", "Compaction extra output fraction")]:
        md.append(f"| {lab} | {v[k]:,.2f} |")
    md.append("")

    # 5. auto-summarization trade-off
    md += ["## Auto-summarisation trigger trade-off (GLM-5.3 FP8 / DSv4 native / Kimi native, cheapest GPU, 90 users, 30 tok/s)", "",
           "| Model | Workload | Effective trigger T | Mean ctx | Extra output for summaries | Own room Rs lakh/mo | Nodes |", "|---|---|---|---|---|---|---|"]
    for m, prec in (("glm53", "fp8"), ("dsv4pro", "native"), ("kimi27", "native")):
        for wl in ("agent_128k", "agent_1m", "stress_1m"):
            b = best(d, m, wl, 90, 30, "buy_m")
            if not b:
                md.append(f"| {NAMES[m]} | {wl} | | | | not feasible | |")
                continue
            v = b[1]
            md.append(f"| {NAMES[m]} | {wl} | {v['c_T']:,.0f} | {v['ctx_mean']:,.0f} | {v['cmp_out_overhead']:.0%} | {L(b[0])} ({v['gpu']} {v['precision']}) | {v['nodes']:.0f} |")
    md.append("")

    # 6. OCR
    md += ["## Chandra OCR 2 (cheapest per tier; 24/7, ITC)", "",
           "| Tier (pages/h peak) | GPU / precision | GPUs | Rent Rs/mo | Bought (existing room) Rs/mo | Rs per 1k pages rent / bought |", "|---|---|---|---|---|---|"]
    for tier, ph in d.ocr["tiers"].items():
        top = None
        for gpu, g in d.ocr["gpus"].items():
            for prec in g["precisions"]:
                v = run_ocr(d.ocr_row(gpu, prec, tier, **BASE))
                cost = min(v["q_rent_m"], v["q_room_m"])
                if top is None or cost < top[0]:
                    top = (cost, gpu, prec, v)
        _, gpu, prec, v = top
        md.append(f"| {tier} ({ph:,}) | {gpu} / {prec} | {v['q_gpus']:.0f} | {v['q_rent_m']:,.0f} | {v['q_room_m']:,.0f} | {v['q_per_1k_rent']:,.1f} / {v['q_per_1k_room']:,.1f} |")
    md += ["", "Chandra OCR 2 licence: no commercial use by entities with >$2M revenue/funding without a paid Datalab licence (not costed).", ""]

    # 7. calibration
    cal = yaml.safe_load(open(DATA / "efficiency.yaml"))["overrides"]
    md += ["## Throughput calibration (no paid benchmark was run)", "",
           "Per-sequence overhead e_seq_us fitted by least squares to published 2026 InferenceX/Lambda points; bandwidth efficiency fixed per GPU family.",
           "Mean |residual| 2.9%, max 17.2% over 12 points. Pairs without data inherit from the nearest measured pair (uncertainty +/-25%).", "",
           "| Pair | e_seq_us | Source |", "|---|---|---|"]
    for k, e in cal.items():
        if "e_seq_us" in e:
            md.append(f"| {k} | {e['e_seq_us']['value']} | {e['e_seq_us']['source']} |")
    md.append("")
    OUT.write_text("\n".join(md))
    print(f"wrote {OUT} ({len(md)} lines)")


if __name__ == "__main__":
    main()
